"""Write cmaps.js: 256-step lookup tables of the matplotlib colormaps the desktop mapping window offers."""
import json
from pathlib import Path

import matplotlib
import numpy as np

NAMES = ["RdBu_r", "viridis", "plasma", "inferno", "magma", "cividis", "coolwarm", "seismic", "hot", "jet", "twilight"]
out = {}
for name in NAMES:
    rgb = (matplotlib.colormaps[name](np.linspace(0, 1, 256))[:, :3] * 255).round().astype(int)
    out[name] = ''.join('%02x%02x%02x' % tuple(c) for c in rgb)
path = Path(__file__).resolve().parent.parent / 'cmaps.js'
path.write_text('// Generated by pages/make_cmaps.py from matplotlib ' + matplotlib.__version__ + ': 256 RGB steps per map, hex.\n'
                'globalThis.DP_CMAPS = ' + json.dumps(out, indent=0) + ';\n', encoding='utf-8')
print('wrote', path, path.stat().st_size, 'bytes')
